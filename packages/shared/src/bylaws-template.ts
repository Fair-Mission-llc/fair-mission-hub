// The outline the Council Bylaws Data Vault (/governance/bylaws) shows while a council has no bylaws saved, and the
// text an editor starts from. It follows the usual article order of a Knights of Columbus council's bylaws. The
// wording is a plain-language starting point written for this platform, not the Supreme Council's official text.
// Bracketed fields are for the council to fill in. Every clause stays subject to the Charter, Constitution and Laws
// of the Order and to Supreme Council policy; the council adopts its bylaws by its own vote and the approval the
// Laws require.
// =========================================================================

/** The template's title line, shown above the preview. */
export const STANDARD_BYLAWS_TEMPLATE_TITLE = 'Standard Knights of Columbus council bylaws template';

/** The template as bylaws markdown: '# ' articles and '## ' sections, so the clause feed numbers it like saved bylaws. */
export const STANDARD_BYLAWS_TEMPLATE = `# Article I - Name and Authority

## Section 1 - Name
This council is known as [Council Name] Council No. [Number], Knights of Columbus.

## Section 2 - Authority
The council works under a charter from the Supreme Council. These bylaws are subject to the Charter, Constitution and Laws of the Order. Where a bylaw conflicts with them, the Charter, Constitution and Laws govern.

# Article II - Purpose

## Section 1 - Purpose
The council carries out the principles of the Order: Charity, Unity, Fraternity and Patriotism. It serves the Church, its parish, its community, its families and its members.

## Section 2 - Parish
The council's home parish is [Parish Name], [City, State].

# Article III - Membership

## Section 1 - Eligibility
Membership is open to practical Catholic men who meet the requirements of the Laws of the Order.

## Section 2 - Admission
An applicant is admitted as the Laws of the Order and Supreme Council policy require.

## Section 3 - Good standing
A member is in good standing while his dues are paid and he is not suspended under the Laws of the Order.

# Article IV - Officers

## Section 1 - Elected officers
The elected officers are the Grand Knight, Deputy Grand Knight, Chancellor, Recorder, Treasurer, Advocate, Warden, Inside Guard, Outside Guards and one Trustee each year.

## Section 2 - Appointed officers
The Grand Knight appoints the Chaplain, the Lecturer and the program and committee directors. The Financial Secretary is appointed by the Supreme Knight on the council's recommendation.

## Section 3 - Trustees
The Board of Trustees has three members, each elected for a three-year term. The Grand Knight is a member of the Board and its chairman.

## Section 4 - Duties
Each officer performs the duties the Laws of the Order and the officers' manuals give the office.

# Article V - Elections

## Section 1 - Time of election
The council elects its officers each year at a regular meeting in [Month], as the Laws of the Order require.

## Section 2 - Nominations
Nominations are made at the meeting before the election meeting and may also be made from the floor at the election.

## Section 3 - Voting
Officers are elected by secret ballot of the members in good standing who are present. A majority of the votes cast elects.

## Section 4 - Term
Officers take office on July 1 and serve one year, or until their successors are installed.

# Article VI - Meetings

## Section 1 - Regular meetings
The council holds a business meeting on the [Week] [Day] of each month at [Time], at [Location].

## Section 2 - Officer meetings
The officers meet each month before the business meeting to prepare its agenda.

## Section 3 - Special meetings
The Grand Knight may call a special meeting. Members receive notice of its time, place and purpose at least [Number] days before.

## Section 4 - Quorum
[Number] members in good standing, including the presiding officer, form a quorum.

## Section 5 - Rules of order
Meetings follow the ceremonials of the Order and, where they are silent, Robert's Rules of Order, Newly Revised.

# Article VII - Dues and Finances

## Section 1 - Dues
Annual dues are $[Amount], payable to the Financial Secretary by [Date]. A change in dues takes a vote of the council at a regular meeting after notice.

## Section 2 - Receipts
The Financial Secretary receives all money paid to the council and transfers it to the Treasurer promptly.

## Section 3 - Disbursements
The Treasurer pays the council's bills by check or approved electronic payment. Each payment needs a voucher signed by the Financial Secretary and the Grand Knight.

## Section 4 - Spending limits
An expense over $[Amount] not in the approved budget needs a vote of the council.

## Section 5 - Budget
The Grand Knight presents a budget for the fraternal year for the council's approval.

## Section 6 - Audit
The Board of Trustees audits the council's books twice each year, as the Laws of the Order require, and reports to the council.

# Article VIII - Committees and Programs

## Section 1 - Program director
The Program Director plans the council's programs with the Faith, Family, Community and Life directors.

## Section 2 - Standing committees
The Grand Knight appoints the chairmen of the standing committees, which include Membership, Retention and Programs.

## Section 3 - Reports
Each committee chairman reports at the regular meeting.

# Article IX - Discipline

## Section 1 - Procedure
Charges against a member follow the procedure in the Laws of the Order.

# Article X - Amendments

## Section 1 - Proposal
A member proposes an amendment in writing at a regular meeting. It is read and laid over to the next regular meeting.

## Section 2 - Adoption
An amendment is adopted by a two-thirds vote of the members present at that meeting, and takes effect when approved as the Laws of the Order require.

# Article XI - Adoption

## Section 1 - Effective date
These bylaws were adopted by the council on [Date] and take effect on [Date].
`;
